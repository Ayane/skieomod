"""Share reviewed native relocation fingerprints between preflight and C."""
from pathlib import Path


def validate(guard):
    data = guard['normalized']
    size, masks = data['size'], data['masks']
    prefix = bytes.fromhex(guard['bytes'])
    if not isinstance(size, int) or not len(prefix) <= size <= 8192 or not prefix:
        raise ValueError('Invalid normalized native code size')
    end = len(prefix)
    if not isinstance(masks, list) or len(masks) > 1024:
        raise ValueError('Invalid native address masks')
    for offset, length in masks:
        if not isinstance(offset, int) or length not in (1, 4) or offset < end or offset + length > size:
            raise ValueError('Invalid/overlapping native address mask')
        end = offset + length
    fingerprint = int(data['fnv1a64'], 16)
    if not 0 <= fingerprint < 2**64:
        raise ValueError('Invalid normalized code fingerprint')
    reference = data.get('rel32_target')
    if reference and (guard['id'] != 'hubs.deferred' or reference.get('layout') != 'hubs.rebuild'
        or reference.get('end') != reference.get('offset', -4) + 4
        or [reference.get('offset'), 4] not in masks or reference['end'] > size):
        raise ValueError('Invalid native layout cross-reference')
    return prefix, size, masks, fingerprint


def fingerprint(code, masks):
    normalized = bytearray(code)
    for offset, length in masks:
        normalized[offset:offset + length] = bytes(length)
    result = 14695981039346656037
    for value in normalized:
        result = ((result ^ value) * 1099511628211) & ((1 << 64) - 1)
    return result


def resolve(image, guard, guards=()):
    prefix, size, masks, expected = validate(guard)
    reference = guard['normalized'].get('rel32_target')
    target = None
    if reference:
        import struct
        other = next((g for g in guards if g['id'] == reference['layout']), None)
        # References are deliberately one level deep to prevent cyclic contracts.
        if not other or other['normalized'].get('rel32_target'):
            raise ValueError('Invalid native layout cross-reference')
        matches = resolve(image, other, guards)
        if len(matches) != 1:
            return []
        target = matches[0]
    found = []
    for rva, length, raw, executable in image.sections:
        if not executable:
            continue
        cursor = raw
        while cursor + size <= raw + length:
            at = image.data.find(prefix, cursor, raw + length - size + len(prefix))
            if at < 0:
                break
            matched = fingerprint(image.data[at:at + size], masks) == expected
            if matched and reference:
                displacement = struct.unpack_from('<i', image.data, at + reference['offset'])[0]
                matched = rva + at - raw + reference['end'] + displacement == target
            if matched:
                found.append(rva + at - raw)
                if len(found) == 2:
                    return found
            cursor = at + 1
    return found


def header(contract):
    guards = [g for g in contract['guards'] if g['mode'] == 'normalized_unique']
    lines = ['/* Generated by tools.native_layouts; no game code snapshots. */',
             '#ifndef SKIEO_LAYOUT_PROFILES_H', '#define SKIEO_LAYOUT_PROFILES_H',
             '#include "layout_resolution.h"', 'enum SkiEOLayoutId {']
    for g in guards:
        lines.append('    SKIEO_LAYOUT_' + g['id'].replace('.', '_').upper() + ',')
    lines += ['    SKIEO_LAYOUT_COUNT', '};']
    for i, g in enumerate(guards):
        prefix, size, masks, expected = validate(g)
        lines.append('static const uint8_t skieo_prefix_%d[] = {%s};' % (i, ','.join('0x%02x' % n for n in prefix)))
        lines.append('static const SkiEOAddressMask skieo_masks_%d[] = {%s};' %
                     (i, ','.join('{%d,%d}' % tuple(m) for m in masks) or '{0,0}'))
    lines.append('static const SkiEOCodeLayout skieo_layouts[] = {')
    for i, g in enumerate(guards):
        prefix, size, masks, expected = validate(g)
        lines.append('    {skieo_prefix_%d,%d,%d,skieo_masks_%d,%d,UINT64_C(0x%016X)},' %
                     (i, len(prefix), size, i, len(masks), expected))
    lines.append('};')
    for g in guards:
        ref = g['normalized'].get('rel32_target')
        if ref:
            key = 'SKIEO_LAYOUT_' + g['id'].replace('.', '_').upper()
            lines += ['#define ' + key + '_TARGET SKIEO_LAYOUT_' + ref['layout'].replace('.', '_').upper(),
                      '#define ' + key + '_OFFSET ' + str(ref['offset']),
                      '#define ' + key + '_END ' + str(ref['end'])]
    return '\n'.join(lines + ['#endif', ''])


if __name__ == '__main__':
    import json
    root = Path(__file__).resolve().parents[1]
    contract = json.loads((root / 'compatibility/game-contract.json').read_text())
    (root / 'native/SkiEONativeTerrain/layout_profiles.h').write_text(header(contract))
